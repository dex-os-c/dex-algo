"""
crypto_alphas.py - Institutional Multi-Alpha Ensemble for Crypto Quantitative Trading
Combines 3 uncorrelated institutional alpha signals specifically engineered for Bitcoin and crypto microstructure:
  1. Alpha 1: Adaptive Trend / Momentum Alpha (Hull Moving Average + Donchian Channel 20 Breakout)
  2. Alpha 2: Mean Reversion Alpha (Bollinger Bands %B + Volume-Weighted RSI 14)
  3. Alpha 3: Microstructure & Order Flow Imbalance (OFI) Alpha (Volume Delta + Order Book Depth Imbalance)

Dynamic Regime Blending:
  Dynamically rebalances alpha weights based on the active regime detected by regime_detector:
    - TRENDING_BULL:             60% Trend, 10% Mean-Rev, 30% OFI
    - TRENDING_BEAR:             60% Trend, 10% Mean-Rev, 30% OFI
    - MEAN_REVERTING_CHOP:       15% Trend, 60% Mean-Rev, 25% OFI
    - HIGH_VOLATILITY_EXPANSION: 30% Breakout, 20% Mean-Rev, 50% OFI
    - Default / Neutral:         34% Trend, 33% Mean-Rev, 33% OFI

Outputs:
  CompositeSignal dataclass with composite_score (-1.0 to +1.0), direction ('BUY', 'SELL', 'NEUTRAL'),
  confidence (0.0 to 1.0), individual alpha scores, and active regime.
"""

import math
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional, Tuple, Union


