@dataclass
class CompositeSignal:
    """
    Unified signal generated by the MultiAlphaEnsemble.
    Normalized score ranges from -1.0 (extreme short/bearish) to +1.0 (extreme long/bullish).
    """
    symbol: str
    composite_score: float              # -1.0 to +1.0
    direction: str                      # 'BUY', 'SELL', 'NEUTRAL'
    confidence: float                   # 0.0 to 1.0
    trend_score: float                  # Alpha 1: -1.0 to +1.0
    mean_rev_score: float               # Alpha 2: -1.0 to +1.0
    ofi_score: float                    # Alpha 3: -1.0 to +1.0
    active_regime: str                  # e.g. 'TRENDING_BULL', 'MEAN_REVERTING_CHOP'
    weights: Dict[str, float]           # {'trend': 0.60, 'mean_rev': 0.10, 'ofi': 0.30}
    timestamp: str = ""
    metadata: Dict[str, Any] = field(default_factory=dict)

    def __post_init__(self):
        if not self.timestamp:
            self.timestamp = datetime.now(timezone.utc).isoformat()
        self.composite_score = round(max(-1.0, min(1.0, float(self.composite_score))), 4)
        self.trend_score = round(max(-1.0, min(1.0, float(self.trend_score))), 4)
        self.mean_rev_score = round(max(-1.0, min(1.0, float(self.mean_rev_score))), 4)
        self.ofi_score = round(max(-1.0, min(1.0, float(self.ofi_score))), 4)
        self.confidence = round(max(0.0, min(1.0, float(self.confidence))), 4)

    @property
    def action(self) -> str:
        """Alias for direction ('BUY', 'SELL', 'NEUTRAL')."""
        return self.direction

    @property
    def regime(self) -> str:
        """Alias for active_regime."""
        return self.active_regime

    @property
    def alpha1_trend(self) -> float:
        """Alias for trend_score."""
        return self.trend_score

    @property
    def alpha2_mean_rev(self) -> float:
        """Alias for mean_rev_score."""
        return self.mean_rev_score

    @property
    def alpha3_ofi(self) -> float:
        """Alias for ofi_score."""
        return self.ofi_score

    @property
    def alpha_scores(self) -> Dict[str, float]:
        """Dictionary of individual alpha scores."""
        return {
            "trend": self.trend_score,
            "mean_reversion": self.mean_rev_score,
            "order_flow": self.ofi_score,
            "ofi": self.ofi_score,
        }

    def to_dict(self) -> Dict[str, Any]:
        """Returns JSON-serializable dictionary."""
        d = asdict(self)
        d["action"] = self.action
        d["regime"] = self.regime
        d["alpha_scores"] = self.alpha_scores
        return d


