class MeanReversionAlpha:
    """
    Alpha 2: Mean Reversion Alpha.
    Uses Bollinger Bands %B and Volume-Weighted RSI (14) to capture mean-reverting exhaustion.
    """

    def __init__(self, bb_period: int = 20, bb_std: float = 2.0, rsi_period: int = 14):
        self.bb_period = bb_period
        self.bb_std = bb_std
        self.rsi_period = rsi_period

    @staticmethod
    def calculate_bollinger_bands(
        prices: List[float], period: int = 20, num_std: float = 2.0
    ) -> Tuple[float, float, float, float]:
        """Computes Bollinger Bands: (Upper, Lower, Middle, %B)."""
        if not prices:
            return 0.0, 0.0, 0.0, 0.5

        sub_prices = prices[-period:] if len(prices) >= period else prices
        n = len(sub_prices)
        current_price = prices[-1]

        mean = sum(sub_prices) / n
        variance = sum((p - mean) ** 2 for p in sub_prices) / n
        std_dev = math.sqrt(variance)

        upper = mean + (num_std * std_dev)
        lower = mean - (num_std * std_dev)
        bandwidth = upper - lower

        pct_b = (current_price - lower) / bandwidth if bandwidth > 1e-6 else 0.5
        return upper, lower, mean, pct_b

    @staticmethod
    def calculate_vw_rsi(bars: List[Dict[str, Any]], period: int = 14) -> float:
        """
        Computes Volume-Weighted RSI (VW-RSI 14).
        Weights price gains and losses by bar volume to capture institutional flow.
        """
        if len(bars) < 2:
            return 50.0

        closes = [float(b.get("close", 0.0)) for b in bars]
        volumes = [float(b.get("volume", 1.0)) for b in bars]

        gains: List[float] = []
        losses: List[float] = []

        for i in range(1, len(closes)):
            delta = closes[i] - closes[i - 1]
            vol = max(1.0, volumes[i])
            if delta > 0:
                gains.append(delta * vol)
                losses.append(0.0)
            else:
                gains.append(0.0)
                losses.append(abs(delta) * vol)

        if not gains:
            return 50.0

        sub_len = min(period, len(gains))
        avg_gain = sum(gains[:sub_len]) / sub_len
        avg_loss = sum(losses[:sub_len]) / sub_len

        for i in range(sub_len, len(gains)):
            gain = gains[i]
            loss = losses[i]
            avg_gain = (avg_gain * (period - 1) + gain) / period
            avg_loss = (avg_loss * (period - 1) + loss) / period

        if avg_loss < 1e-9:
            return 100.0 if avg_gain > 0 else 50.0
        if avg_gain < 1e-9:
            return 0.0

        rs = avg_gain / avg_loss
        vw_rsi = 100.0 - (100.0 / (1.0 + rs))
        return round(vw_rsi, 2)

    def compute_score(self, bars: List[Dict[str, Any]]) -> float:
        """
        Computes normalized Alpha 2 score from -1.0 (extreme overbought / sell) to +1.0 (extreme oversold / buy).
        """
        if not bars or len(bars) < 2:
            return 0.0

        closes = [float(b.get("close", 0.0)) for b in bars]
        _, _, _, pct_b = self.calculate_bollinger_bands(closes, self.bb_period, self.bb_std)
        vw_rsi = self.calculate_vw_rsi(bars, self.rsi_period)

        # Extreme Bounce / Exhaustion Conditions
        if pct_b < 0.05 and vw_rsi < 30.0:
            b_boost = max(0.0, (0.05 - pct_b) / 0.05) * 0.10
            rsi_boost = max(0.0, (30.0 - vw_rsi) / 30.0) * 0.10
            return round(min(1.0, 0.80 + b_boost + rsi_boost), 4)

        if pct_b > 0.95 and vw_rsi > 70.0:
            b_boost = max(0.0, (pct_b - 0.95) / 0.05) * 0.10
            rsi_boost = max(0.0, (vw_rsi - 70.0) / 30.0) * 0.10
            return round(max(-1.0, -(0.80 + b_boost + rsi_boost)), 4)

        # Continuous Mean Reversion Mapping
        b_component = (0.5 - pct_b) * 2.0
        rsi_component = (50.0 - vw_rsi) / 50.0
        raw_score = 0.55 * b_component + 0.45 * rsi_component

        if 0.35 <= pct_b <= 0.65 and 42.0 <= vw_rsi <= 58.0:
            raw_score *= 0.25

        return round(max(-1.0, min(1.0, raw_score)), 4)

    def get_diagnostics(self, bars: List[Dict[str, Any]]) -> Dict[str, Any]:
        """Returns indicator breakdown for Alpha 2."""
        if not bars:
            return {}
        closes = [float(b.get("close", 0.0)) for b in bars]
        upper, lower, mid, pct_b = self.calculate_bollinger_bands(closes, self.bb_period, self.bb_std)
        vw_rsi = self.calculate_vw_rsi(bars, self.rsi_period)
        score = self.compute_score(bars)

        return {
            "alpha": "MeanRev_BB_VWRSI",
            "score": score,
            "bb_upper": round(upper, 2),
            "bb_lower": round(lower, 2),
            "bb_mid": round(mid, 2),
            "pct_b": round(pct_b, 4),
            "vw_rsi": round(vw_rsi, 2),
            "oversold_trigger": pct_b < 0.05 and vw_rsi < 30.0,
            "overbought_trigger": pct_b > 0.95 and vw_rsi > 70.0,
        }


