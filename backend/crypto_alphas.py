class OrderFlowImbalanceAlpha:
    """
    Alpha 3: Microstructure & Order Flow Imbalance (OFI) Alpha.
    Calculates Volume Delta (Taker Buy vs Taker Sell Volume) and Order Book Depth Imbalance:
      - Depth Imbalance = (Bid Vol - Ask Vol) / (Bid Vol + Ask Vol)
      - Volume Delta Ratio = (Taker Buy Vol - Taker Sell Vol) / (Taker Buy Vol + Taker Sell Vol)
    """

    def __init__(self, depth_levels: int = 10, lookback_bars: int = 5):
        self.depth_levels = depth_levels
        self.lookback_bars = lookback_bars

    @staticmethod
    def calculate_depth_imbalance(
        orderbook: Optional[Dict[str, Any]], depth_levels: int = 10
    ) -> float:
        """Calculates order book depth imbalance across top depth_levels."""
        if not orderbook:
            return 0.0

        if "bid_volume" in orderbook and "ask_volume" in orderbook:
            b_vol = float(orderbook["bid_volume"])
            a_vol = float(orderbook["ask_volume"])
            tot = b_vol + a_vol
            return (b_vol - a_vol) / tot if tot > 0 else 0.0

        if "bid_depth" in orderbook and "ask_depth" in orderbook:
            b_vol = float(orderbook["bid_depth"])
            a_vol = float(orderbook["ask_depth"])
            tot = b_vol + a_vol
            return (b_vol - a_vol) / tot if tot > 0 else 0.0

        bids = orderbook.get("bids", [])[:depth_levels]
        asks = orderbook.get("asks", [])[:depth_levels]

        def sum_depth(orders: list) -> float:
            total = 0.0
            for o in orders:
                if isinstance(o, (list, tuple)) and len(o) >= 2:
                    total += float(o[1])
                elif isinstance(o, dict):
                    total += float(o.get("size", o.get("amount", o.get("quantity", 0.0))))
            return total

        bid_vol = sum_depth(bids)
        ask_vol = sum_depth(asks)
        tot = bid_vol + ask_vol
        return (bid_vol - ask_vol) / tot if tot > 1e-9 else 0.0

    @staticmethod
    def calculate_volume_delta(
        taker_buy_vol: Optional[float] = None, taker_sell_vol: Optional[float] = None
    ) -> Optional[float]:
        """Calculates normalized Volume Delta Ratio."""
        if taker_buy_vol is None or taker_sell_vol is None:
            return None
        tot = taker_buy_vol + taker_sell_vol
        return (taker_buy_vol - taker_sell_vol) / tot if tot > 1e-9 else 0.0

    @staticmethod
    def estimate_volume_delta_from_bars(
        bars: List[Dict[str, Any]], lookback: int = 5
    ) -> float:
        """Estimates volume delta from recent candle bars using intra-bar price action."""
        if not bars:
            return 0.0

        sub_bars = bars[-lookback:] if len(bars) >= lookback else bars
        net_delta = 0.0
        tot_vol = 0.0

        for b in sub_bars:
            h = float(b.get("high", 0.0))
            l = float(b.get("low", 0.0))
            c = float(b.get("close", 0.0))
            v = float(b.get("volume", 0.0))

            tot_vol += v
            candle_range = h - l
            if candle_range > 1e-6:
                buy_ratio = (c - l) / candle_range
                delta = v * (2.0 * buy_ratio - 1.0)
            else:
                delta = 0.0
            net_delta += delta

        return (net_delta / tot_vol) if tot_vol > 1e-9 else 0.0

    def compute_score(
        self,
        orderbook: Optional[Dict[str, Any]] = None,
        taker_buy_vol: Optional[float] = None,
        taker_sell_vol: Optional[float] = None,
        bars: Optional[List[Dict[str, Any]]] = None,
    ) -> float:
        """Computes normalized Alpha 3 score from -1.0 to +1.0."""
        depth_imbalance = self.calculate_depth_imbalance(orderbook, self.depth_levels)
        vol_delta_ratio = self.calculate_volume_delta(taker_buy_vol, taker_sell_vol)

        if vol_delta_ratio is None and bars:
            vol_delta_ratio = self.estimate_volume_delta_from_bars(bars, self.lookback_bars)

        if orderbook is not None and vol_delta_ratio is not None:
            score = 0.50 * depth_imbalance + 0.50 * vol_delta_ratio
        elif orderbook is not None:
            score = depth_imbalance
        elif vol_delta_ratio is not None:
            score = vol_delta_ratio
        else:
            score = 0.0

        return round(max(-1.0, min(1.0, score)), 4)

    def get_diagnostics(
        self,
        orderbook: Optional[Dict[str, Any]] = None,
        taker_buy_vol: Optional[float] = None,
        taker_sell_vol: Optional[float] = None,
        bars: Optional[List[Dict[str, Any]]] = None,
    ) -> Dict[str, Any]:
        """Returns microstructure metrics breakdown for Alpha 3."""
        depth_imb = self.calculate_depth_imbalance(orderbook, self.depth_levels)
        vol_delta = self.calculate_volume_delta(taker_buy_vol, taker_sell_vol)
        if vol_delta is None and bars:
            vol_delta = self.estimate_volume_delta_from_bars(bars, self.lookback_bars)
        score = self.compute_score(orderbook, taker_buy_vol, taker_sell_vol, bars)

        return {
            "alpha": "Microstructure_OFI",
            "score": score,
            "depth_imbalance": round(depth_imb, 4),
            "volume_delta_ratio": round(vol_delta, 4) if vol_delta is not None else 0.0,
            "has_orderbook": orderbook is not None,
            "has_taker_flow": taker_buy_vol is not None,
        }


