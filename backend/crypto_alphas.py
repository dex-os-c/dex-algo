class AdaptiveTrendAlpha:
    """
    Alpha 1: Adaptive Trend / Momentum Alpha.
    Combines Hull Moving Average (HMA) with Donchian Channel (20) breakout detection.
    """

    def __init__(self, hma_period: int = 20, donchian_period: int = 20):
        self.hma_period = hma_period
        self.donchian_period = donchian_period

    @staticmethod
    def calculate_wma(prices: List[float], period: int) -> List[float]:
        """Computes Weighted Moving Average (WMA) for a price series."""
        if not prices:
            return []
        n = len(prices)
        if period <= 1:
            return [float(p) for p in prices]

        wma_list: List[float] = []
        denom = (period * (period + 1)) // 2

        for i in range(n):
            if i + 1 < period:
                sub = prices[: i + 1]
                sub_k = len(sub)
                sub_denom = (sub_k * (sub_k + 1)) // 2
                w_sum = sum((idx + 1) * p for idx, p in enumerate(sub))
                wma_list.append(w_sum / sub_denom)
            else:
                window = prices[i - period + 1 : i + 1]
                w_sum = sum((idx + 1) * p for idx, p in enumerate(window))
                wma_list.append(w_sum / denom)

        return wma_list

    @staticmethod
    def calculate_hma(prices: List[float], period: int = 20) -> List[float]:
        """
        Computes Hull Moving Average (HMA):
          HMA = WMA(floor(sqrt(period)), 2 * WMA(period/2) - WMA(period))
        """
        if not prices:
            return []
        if len(prices) < 3:
            return [float(p) for p in prices]

        half_period = max(1, period // 2)
        sqrt_period = max(1, int(math.isqrt(period)))

        wma_half = AdaptiveTrendAlpha.calculate_wma(prices, half_period)
        wma_full = AdaptiveTrendAlpha.calculate_wma(prices, period)

        diff_series = [2.0 * h - f for h, f in zip(wma_half, wma_full)]
        hma_series = AdaptiveTrendAlpha.calculate_wma(diff_series, sqrt_period)
        return hma_series

    @staticmethod
    def calculate_donchian_channel(bars: List[Dict[str, Any]], period: int = 20) -> Tuple[float, float, float]:
        """Calculates Donchian Channel (20): (Upper, Lower, Mid)."""
        if not bars:
            return 0.0, 0.0, 0.0

        sub_bars = bars[-period:] if len(bars) >= period else bars
        highs = [float(b.get("high", b.get("close", 0.0))) for b in sub_bars]
        lows = [float(b.get("low", b.get("close", 0.0))) for b in sub_bars]

        upper = max(highs) if highs else 0.0
        lower = min(lows) if lows else 0.0
        mid = (upper + lower) / 2.0
        return upper, lower, mid

    def compute_score(self, bars: List[Dict[str, Any]]) -> float:
        """
        Computes normalized Alpha 1 trend score from -1.0 (strong short) to +1.0 (strong long).
        """
        if not bars or len(bars) < 2:
            return 0.0

        closes = [float(b.get("close", 0.0)) for b in bars]
        current_price = closes[-1]

        # 1. Hull Moving Average Trend Direction & Slope
        hma_series = self.calculate_hma(closes, self.hma_period)
        current_hma = hma_series[-1] if hma_series else current_price
        prev_hma = hma_series[-2] if len(hma_series) >= 2 else current_hma

        hma_slope = (current_hma - prev_hma) / prev_hma if prev_hma > 0 else 0.0
        price_diff = (current_price - current_hma) / current_hma if current_hma > 0 else 0.0

        hma_slope_score = math.tanh(hma_slope * 250.0)
        hma_pos_score = math.tanh(price_diff * 60.0)
        hma_score = 0.65 * hma_slope_score + 0.35 * hma_pos_score

        # 2. Donchian Channel Breakout
        upper, lower, mid = self.calculate_donchian_channel(bars, self.donchian_period)
        channel_width = upper - lower

        if channel_width > 1e-6:
            if current_price >= upper:
                donchian_score = 1.0
            elif current_price <= lower:
                donchian_score = -1.0
            else:
                half_width = channel_width / 2.0
                donchian_score = (current_price - mid) / half_width
        else:
            donchian_score = 0.0

        donchian_score = max(-1.0, min(1.0, donchian_score))
        raw_trend = 0.50 * donchian_score + 0.50 * hma_score
        return round(max(-1.0, min(1.0, raw_trend)), 4)

    def get_diagnostics(self, bars: List[Dict[str, Any]]) -> Dict[str, Any]:
        """Returns indicator breakdown for Alpha 1."""
        if not bars:
            return {}
        closes = [float(b.get("close", 0.0)) for b in bars]
        hma_series = self.calculate_hma(closes, self.hma_period)
        upper, lower, mid = self.calculate_donchian_channel(bars, self.donchian_period)
        score = self.compute_score(bars)

        return {
            "alpha": "Trend_HMA_Donchian",
            "score": score,
            "hma": round(hma_series[-1], 2) if hma_series else 0.0,
            "donchian_upper": round(upper, 2),
            "donchian_lower": round(lower, 2),
            "donchian_mid": round(mid, 2),
            "close": round(closes[-1], 2),
        }


